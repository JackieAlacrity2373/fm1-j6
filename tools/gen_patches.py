"""Regenerates editor/patches.js from the factory table in src/juno.c, so the web editor and the firmware agree.
   python tools/gen_patches.py"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "src", "juno.c"), encoding="utf-8").read()

init = re.search(r"static const uint8_t V\[28\] = \{([^}]*)\}", src)
fac = re.findall(r'\{"([^"]{8})", \{([^}]*)\}\}', src)
if not init or not fac:
    sys.exit("could not find the patch tables in src/juno.c")


def nums(s):
    v = [int(x) for x in s.split(",")]
    if len(v) != 28:
        sys.exit("a patch does not have 28 values: " + s)
    return v


out = ["// Generated by tools/gen_patches.py from src/juno.c. Do not edit.",
       "// Values are in the order of J6_FIELDS (params.js): the j_patch_t fields after the name.",
       "const J6_INIT = %s;" % nums(init.group(1)),
       "const J6_FACTORY = ["]
for name, vals in fac:
    out.append('  {name: "%s", v: %s},' % (name, nums(vals)))
out.append("];")
os.makedirs(os.path.join(ROOT, "editor"), exist_ok=True)
open(os.path.join(ROOT, "editor", "patches.js"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote editor/patches.js: %d factory patches" % len(fac))
